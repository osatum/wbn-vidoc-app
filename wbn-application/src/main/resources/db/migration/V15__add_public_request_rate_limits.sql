CREATE TABLE public_request_limit (
    bucket_key varchar(96) PRIMARY KEY,
    expires_at timestamp with time zone NOT NULL,
    blocked_until timestamp with time zone
);

CREATE INDEX idx_public_request_limit_expiry ON public_request_limit (expires_at);

CREATE TABLE public_request_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_key varchar(96) NOT NULL REFERENCES public_request_limit (bucket_key) ON DELETE CASCADE,
    occurred_at timestamp with time zone NOT NULL
);

CREATE INDEX idx_public_request_attempt_window ON public_request_attempt (bucket_key, occurred_at);
